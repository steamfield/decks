"""Write data/noaa.generated.ts from the NOAA GML Mauna Loa CSVs.

Usage: python3 -I examples/keeling/scripts/extract.py <dir with the three CSVs> [out dir]

The out dir defaults to the deck's data/. The CSVs and their URLs are listed in
data-sources.md. The output is plain numbers; labels and derived values are
computed in the hand-written data/*.ts modules that import it.

Exits non-zero, writing nothing, on an empty cell, a NOAA missing-value
sentinel (-99.99, -9.99) or any value that is not above zero in the columns it
reads: average, mean and ann inc.
"""
import csv
import json
import os
import sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')


def rows(name):
    with open(os.path.join(src, name)) as f:
        return list(csv.DictReader(l for l in f if not l.startswith('#')))


def ppm(name, i, r, col):
    """A ppm cell as a float; exits on an empty cell, a sentinel or a value not above zero."""
    cell = (r.get(col) or '').strip()
    value = float(cell) if cell else None
    if value is None or value in (-99.99, -9.99) or value <= 0:
        sys.exit(f'{name}: row {i + 1} ({r.get("year")}) has {col} = {cell!r}; refusing to write')
    return value


mm = rows('co2_mm_mlo.csv')
an = rows('co2_annmean_mlo.csv')
gr = rows('co2_gr_mlo.csv')

monthly = [{'year': int(r['year']), 'month': int(r['month']), 'x': float(r['decimal date']), 'y': ppm('co2_mm_mlo.csv', i, r, 'average')} for i, r in enumerate(mm)]
annual = [{'x': int(r['year']), 'y': ppm('co2_annmean_mlo.csv', i, r, 'mean')} for i, r in enumerate(an)]
growth = [{'year': int(r['year']), 'ppm': ppm('co2_gr_mlo.csv', i, r, 'ann inc')} for i, r in enumerate(gr)]

header = '// Generated by examples/keeling/scripts/extract.py from NOAA GML CSVs. Do not edit.\n'
with open(os.path.join(out, 'noaa.generated.ts'), 'w') as f:
    f.write(header)
    f.write('export const MONTHLY = ' + json.dumps(monthly) + ' as const\n')
    f.write('export const ANNUAL = ' + json.dumps(annual) + ' as const\n')
    f.write('export const GROWTH = ' + json.dumps(growth) + ' as const\n')
