"""Write data/*.generated.ts from the NOAA GML Mauna Loa CSVs.

Usage: python3 -I decks/keeling/scripts/extract.py <dir with the three CSVs>

The CSVs and their URLs are listed in data-sources.md. Each output is plain
numbers; labels and derived values are computed in the hand-written data/*.ts
modules that import them.
"""
import csv
import json
import os
import sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')


def rows(name):
    with open(os.path.join(src, name)) as f:
        return list(csv.DictReader(l for l in f if not l.startswith('#')))


mm = rows('co2_mm_mlo.csv')
an = rows('co2_annmean_mlo.csv')
gr = rows('co2_gr_mlo.csv')

monthly = [{'year': int(r['year']), 'month': int(r['month']), 'x': float(r['decimal date']), 'y': float(r['average'])} for r in mm]
annual = [{'x': int(r['year']), 'y': float(r['mean'])} for r in an]
growth = [{'year': int(r['year']), 'ppm': float(r['ann inc'])} for r in gr]

header = '// Generated by decks/keeling/scripts/extract.py from NOAA GML CSVs. Do not edit.\n'
with open(os.path.join(out, 'noaa.generated.ts'), 'w') as f:
    f.write(header)
    f.write('export const MONTHLY = ' + json.dumps(monthly) + ' as const\n')
    f.write('export const ANNUAL = ' + json.dumps(annual) + ' as const\n')
    f.write('export const GROWTH = ' + json.dumps(growth) + ' as const\n')
