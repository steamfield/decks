// Write data/sojs.generated.ts from the State of JavaScript survey export.
//
// Usage: node examples/state-of-js/scripts/extract.mjs [raw dir] [out dir]
//
// The raw dir defaults to the deck's data/raw/, which holds the two CSVs and
// SOURCE.md (dataset, API requests, license). The out dir defaults to data/.
// The output is the rows as plain numbers; every derived value is computed in
// the hand-written data/*.ts modules that import it.
//
// Exits non-zero, writing nothing, on a header that does not match, an empty
// cell, a ratio outside 0 to 1, a year outside 2016 to 2025, or a repeated
// tool and year.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = process.argv[2] ?? join(here, '..', 'data', 'raw')
const out = process.argv[3] ?? join(here, '..', 'data')

function fail(msg) {
  console.error(`extract.mjs: ${msg}; refusing to write`)
  process.exit(1)
}

/** Rows of a plain CSV (the export has no quoted cells), checked against an exact header. */
function rows(name, header) {
  const lines = readFileSync(join(src, name), 'utf8').trim().split(/\r?\n/)
  if (lines[0] !== header.join(',')) fail(`${name} header is ${JSON.stringify(lines[0])}`)
  return lines.slice(1).map((line, i) => {
    const cells = line.split(',')
    if (cells.length !== header.length || cells.some((c) => c.trim() === '')) fail(`${name} row ${i + 2} is ${JSON.stringify(line)}`)
    return Object.fromEntries(header.map((h, j) => [h, cells[j].trim()]))
  })
}

function ratio(name, r, col) {
  const v = Number(r[col])
  if (!Number.isFinite(v) || v < 0 || v > 1) fail(`${name} ${r['Tool ID']} ${r.Year ?? ''} has ${col} = ${r[col]}`)
  return v
}

function count(name, r, col) {
  const v = Number(r[col])
  if (!Number.isInteger(v) || v < 0) fail(`${name} ${r['Tool ID']} has ${col} = ${r[col]}`)
  return v
}

const HIST = 'tools_historical.csv'
const CUR = 'tools_2025.csv'

const seen = new Set()
const historical = rows(HIST, ['Tool ID', 'Tool', 'Year', 'Respondents', 'Awareness', 'Usage', 'Interest', 'Retention']).map((r) => {
  const year = Number(r.Year)
  if (!Number.isInteger(year) || year < 2016 || year > 2025) fail(`${HIST} ${r['Tool ID']} has Year = ${r.Year}`)
  const key = `${r['Tool ID']}:${year}`
  if (seen.has(key)) fail(`${HIST} repeats ${key}`)
  seen.add(key)
  return {
    id: r['Tool ID'],
    name: r.Tool,
    year,
    respondents: count(HIST, r, 'Respondents'),
    awareness: ratio(HIST, r, 'Awareness'),
    usage: ratio(HIST, r, 'Usage'),
    interest: ratio(HIST, r, 'Interest'),
    retention: ratio(HIST, r, 'Retention'),
  }
})

const tools2025 = rows(CUR, ['Tool ID', 'Tool', 'Category', 'Respondents', 'Awareness', 'Usage', 'Interest', 'Retention', 'Used', 'Never Heard']).map((r) => ({
  id: r['Tool ID'],
  name: r.Tool,
  category: r.Category,
  respondents: count(CUR, r, 'Respondents'),
  awareness: ratio(CUR, r, 'Awareness'),
  usage: ratio(CUR, r, 'Usage'),
  interest: ratio(CUR, r, 'Interest'),
  retention: ratio(CUR, r, 'Retention'),
  used: count(CUR, r, 'Used'),
  neverHeard: count(CUR, r, 'Never Heard'),
}))

const body =
  '// Generated by examples/state-of-js/scripts/extract.mjs from data/raw/*.csv. Do not edit.\n' +
  '// Source: State of JavaScript (Devographics), via OpenData state-of-survey/state-of-js, CC-BY-4.0. See data/raw/SOURCE.md.\n' +
  `export const HISTORICAL = ${JSON.stringify(historical)} as const\n` +
  `export const TOOLS_2025 = ${JSON.stringify(tools2025)} as const\n`

writeFileSync(join(out, 'sojs.generated.ts'), body)
console.log(`wrote ${historical.length} historical rows and ${tools2025.length} 2025 rows to ${join(out, 'sojs.generated.ts')}`)
