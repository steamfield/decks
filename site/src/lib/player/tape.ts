// What the landing page knows about one example deck, as props for the player.
// Built at build time by src/data/tapes.ts from the deck's own files and from
// fixtures/tapes/<name>.json, which `make demo` records from the built deck.

/** Cassette colors, read from the deck's resolved theme (its theme.json over default.json). */
export type TapeTheme = {
  /** surfaces.canvas: the label's print and the reel hubs. */
  ink: string;
  /** text.primary: the label paper. */
  paper: string;
  /** ramps.cyan/amber/rose step 2: the stripe band across the label. */
  stripes: [string, string, string];
  /** brand.name: printed on the label's corner. */
  brand: string;
  /** The cassette shell: clear, smoke, or a translucent tint of one of the deck's ramps. */
  shell: Shell;
};

export type Shell = { kind: "clear" | "smoke" } | { kind: "tint"; color: string };

/** One beat as the deck reported it while `make demo` walked it. */
export type TapeState = { slide: number; beat: number; beats: number; lead: string; body: string };

/** Generated by `make demo` at 640 and 1280 wide, AVIF and WebP: `${base}-1280.avif`. */
export type Poster = { base: string; width: number; height: number };

export const POSTER_WIDTHS = [640, 1280] as const;

/** srcset for one format: "/posters/tides-640.avif 640w, /posters/tides-1280.avif 1280w". */
export const posterSrcset = (poster: Poster, ext: "avif" | "webp") =>
  POSTER_WIDTHS.map((width) => `${poster.base}-${width}.${ext} ${width}w`).join(", ");

export type Tape = {
  /** Directory name under examples/, and the path segment under /demo/. */
  name: string;
  title: string;
  /** The static build: /demo/<name>/. */
  href: string;
  slides: number;
  slideTitles: string[];
  /** The first story slide, where the poster is taken and PLAY starts. */
  startSlide: number;
  /** The step on the start slide the poster shows and PLAY starts from (0-based). */
  startBeat: number;
  states: TapeState[];
  theme: TapeTheme;
  /** Generated by `make demo`; null until it has run. */
  poster: Poster | null;
};

/** Where a position sits in the recorded walk: 0-based index and the number of steps. */
export function tapePosition(tape: Pick<Tape, "states">, slide: number, beat: number) {
  const total = tape.states.length;
  const exact = tape.states.findIndex((state) => state.slide === slide && state.beat === beat);
  if (exact !== -1) return { index: exact, total };
  // Not recorded (a newer build): the last recorded step before it.
  const before = tape.states.filter(
    (state) => state.slide < slide || (state.slide === slide && state.beat < beat),
  ).length;
  return { index: Math.max(0, before - 1), total };
}

/**
 * Tape pack radii for the two hubs, as fractions of the largest pack. The packs
 * keep the tape's area constant, so radius goes with the square root of length.
 */
export function packRadii(progress: number, core = 0.36) {
  const p = Math.min(1, Math.max(0, progress));
  const radius = (share: number) => Math.sqrt(core ** 2 + (1 - core ** 2) * share);
  return { supply: radius(1 - p), takeup: radius(p) };
}

/** Splits a tracklist into the two sides of a J-card: side A gets the extra track. */
export function sides<T>(tracks: readonly T[]) {
  const half = Math.ceil(tracks.length / 2);
  return { a: tracks.slice(0, half), b: tracks.slice(half) };
}

/** The recorded state for a position, if `make demo` captured one. */
export const stateAt = (tape: Tape, slide: number, beat: number) =>
  tape.states.find((state) => state.slide === slide && state.beat === beat);
